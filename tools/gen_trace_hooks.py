#!/usr/bin/env python3
"""Generate D3D trace hooks: one REX_HOOK_RAW per recompiled function in an
address range, each calling tenchuz::d3d_trace::Record() while a capture runs.

Usage:
  gen_trace_hooks.py [--start 0x8240C000] [--end 0x82450000] [--exclude 0x8241BF50 ...]
                     [--init generated/default/tenchuz_init.cpp]
                     [--out src/renderer/d3d_trace_hooks.gen.cpp]

Functions hooked elsewhere (D3D Swap in frame_stats.cpp) must be excluded, or
the link fails with duplicate symbols. Only plain sub_XXXXXXXX functions are
hooked. Rerun after codegen changes the function set.
"""
import argparse
import re

parser = argparse.ArgumentParser()
parser.add_argument("--start", default="0x8240C000")
parser.add_argument("--end", default="0x82450000")
# 0x8241BF50: D3D Swap, hooked in frame_stats.cpp. 0x82425790: GPU-wait spin loop
# (~500k calls per frame, would flood the capture buffer). 0x8241B308 Clear and
# 0x8241D770 Resolve, 0x8241A780 SetRenderTarget, 0x8241C790 BeginTiling: hooked in
# renderer/native_renderer.cpp (HookScope keeps them traced).
parser.add_argument("--exclude", nargs="*",
                    default=["0x8241BF50", "0x82425790", "0x8241B308", "0x8241D770", "0x8241A780",
                             "0x8241C790"])
parser.add_argument("--init", default="generated/default/tenchuz_init.cpp")
parser.add_argument("--out", default="src/renderer/d3d_trace_hooks.gen.cpp")
args = parser.parse_args()

start, end = int(args.start, 16), int(args.end, 16)
exclude = {int(x, 16) for x in args.exclude}
rx = re.compile(r"\{\s*0x([0-9A-Fa-f]{8}),\s*(sub_[0-9A-Fa-f]{8})\s*\}")
funcs = []
for line in open(args.init, encoding="utf-8"):
    m = rx.search(line)
    if m:
        addr = int(m.group(1), 16)
        if start <= addr < end and addr not in exclude and m.group(2) == f"sub_{addr:08X}":
            funcs.append(addr)
funcs = sorted(set(funcs))

with open(args.out, "w", newline="\n") as o:
    o.write(f"""// GENERATED by tools/gen_trace_hooks.py - do not edit.
// {len(funcs)} trace hooks for 0x{start:08X}-0x{end:08X} (excluding {', '.join(f'0x{x:08X}' for x in sorted(exclude))}).

#include "generated/default/tenchuz_pch.h"

#include <rex/hook.h>

#include "d3d_trace.h"
#include "gpu_observer.h"

#define TENCHUZ_TRACE_HOOK(addr)                                \\
  REX_EXTERN(__imp__sub_##addr);                                \\
  REX_HOOK_RAW(sub_##addr) {{                                    \\
    if (tenchuz::d3d_trace::Active()) {{                         \\
      tenchuz::d3d_trace::Record(0x##addr, ctx);                \\
    }}                                                           \\
    const bool observe = tenchuz::gpu_observer::Active();       \\
    if (observe) {{                                              \\
      tenchuz::gpu_observer::Enter(0x##addr, base);             \\
    }}                                                           \\
    __imp__sub_##addr(ctx, base);                               \\
    if (observe) {{                                              \\
      tenchuz::gpu_observer::Exit(0x##addr, base);              \\
    }}                                                           \\
  }}

""")
    for a in funcs:
        o.write(f"TENCHUZ_TRACE_HOOK({a:08X})\n")
print(f"{len(funcs)} hooks -> {args.out}")
